// Generates the PREPARED (never auto-run) conditional category & warehouse locks migration and its rollback:
//   candidate = database/inventory_atomic.sql
//   rollback target = qa/fixtures/inventory_atomic.main-81e3dab.sql (main 81e3dab)
// `node qa/build-conditional-locks-migration.mjs --check` fails when committed files drift from sources.
import fs from 'node:fs';

const read = (p) => fs.readFileSync(new URL(p, import.meta.url), 'utf8');

// Production md5(prosrc) pins observed on main 81e3dab before this migration.
export const PROD_COMMIT_MD5 = '88df3f4de1eb23fb440ad091a9402625';
export const PROD_VALIDATE_MD5 = 'b4111cae7005ce3380c70ca121b00307';
export const PROD_VALIDATE_CATEGORY_MD5 = 'b9190e8cbaff6216b4c519a28a882287';
// The candidate also replaces these three functions; they are pinned too so the migration never overwrites an
// unreviewed production body (values re-read read-only from production on 2026-11-20 and equal to PGlite main 81e3dab).
export const PROD_RESERVE_CODE_MD5 = '845a453581a58afeb4382b323a427dee';
export const PROD_EVALUATE_REGISTRY_MD5 = '2b608065aa5ecdfb1d38d7b98ba319ce';
export const PROD_RESTORE_PREVIEW_MD5 = '5706fc8322d1bd2df2f8292eb0296c40';
export const PINS = {
  commit_inventory: PROD_COMMIT_MD5,
  validate_inventory: PROD_VALIDATE_MD5,
  validate_category_config: PROD_VALIDATE_CATEGORY_MD5,
  reserve_material_code: PROD_RESERVE_CODE_MD5,
  evaluate_backup_registry: PROD_EVALUATE_REGISTRY_MD5,
  restore_preview: PROD_RESTORE_PREVIEW_MD5,
};
const pinMismatch = () => Object.entries(PINS).map(([name, md5]) => `${fnMd5(name)} IS DISTINCT FROM '${md5}'`).join('\n     OR ');
const pinReport = () => Object.keys(PINS).map((name) => `'${name}='||coalesce(${fnMd5(name)},'<missing>')`).join("||' '||");

const fnMd5 = (name) =>
  `(SELECT md5(p.prosrc) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='inventory_private' AND p.proname='${name}')`;

export function buildMigration(candidate = read('../database/inventory_atomic.sql')) {
  return `-- Conditional Category & Warehouse Locks — PRODUCTION MIGRATION (PREPARED ONLY; NOT AUTO-RUN).
-- Source: database/inventory_atomic.sql (generated by qa/build-conditional-locks-migration.mjs).
-- Baseline pin: main 81e3dab7ff64b7be079a2f4d7b6fe6f47383214c
--   commit_inventory         = ${PROD_COMMIT_MD5}
--   validate_inventory       = ${PROD_VALIDATE_MD5}
--   validate_category_config = ${PROD_VALIDATE_CATEGORY_MD5}
--   reserve_material_code    = ${PROD_RESERVE_CODE_MD5}
--   evaluate_backup_registry = ${PROD_EVALUATE_REGISTRY_MD5}
--   restore_preview          = ${PROD_RESTORE_PREVIEW_MD5}
--
-- Changes:
--   1. Unpins unused categories in validate_category_config while keeping used prefixes locked in category_policy.
--   2. Automatically records prefixes in inventory_private.category_policy on first use (create, code/category edit, restore).
--   3. Adds inventory_private.warehouse_usage (private, no client grants) and records used warehouse IDs automatically.
--   4. Prevents deleting used warehouses in validate_inventory with INVENTORY_WAREHOUSE_IN_USE (renaming/deactivating allowed).
--   5. Adds public.inventory_reference_usage() read RPC for Settings UI lock badges.
--   6. Allows restoring an empty BackupV2 (0 materials, 0 transactions) onto an empty code registry and resolves unpinned prefixes.
--
-- Execution: run in ONE plain session (psql -v ON_ERROR_STOP=1 -f database/migrations/CONDITIONAL_LOCKS_MIGRATION.sql).
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(824671520);
DO $cl_pre$
BEGIN
  IF ${pinMismatch()} THEN
    RAISE EXCEPTION 'CONDITIONAL_LOCKS_BASELINE_DRIFT % (expected main 81e3dab). Stop and re-review.', ${pinReport()};
  END IF;
  IF to_regclass('inventory_private.material_code_registry') IS NULL OR to_regclass('inventory_private.category_policy') IS NULL THEN
    RAISE EXCEPTION 'CONDITIONAL_LOCKS_R8_NOT_APPLIED';
  END IF;
END $cl_pre$;

${candidate}
DO $cl_post$
BEGIN
  PERFORM inventory_private.validate_inventory();
END $cl_post$;
COMMIT;
`;
}

export function buildRollback(main81e3dab = read('./fixtures/inventory_atomic.main-81e3dab.sql')) {
  return `-- Conditional Category & Warehouse Locks — ROLLBACK to main 81e3dab (PREPARED ONLY; NOT AUTO-RUN).
-- Restores the exact main 81e3dab functions and drops the newly added reference_usage / record_warehouse_usage functions.
-- Keeps inventory_private.warehouse_usage (private, no grants, inert under main 81e3dab) and re-validates inventory.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(824671520);

DROP FUNCTION IF EXISTS public.inventory_reference_usage();
DROP FUNCTION IF EXISTS inventory_private.reference_usage();
DROP FUNCTION IF EXISTS inventory_private.record_warehouse_usage(text);

${main81e3dab}

DO $cl_rb_post$
BEGIN
  IF ${pinMismatch()} THEN
    RAISE EXCEPTION 'CONDITIONAL_LOCKS_ROLLBACK_VERIFY_FAILED %', ${pinReport()};
  END IF;
  IF to_regprocedure('inventory_private.reference_usage()') IS NOT NULL OR to_regprocedure('public.inventory_reference_usage()') IS NOT NULL
     OR to_regprocedure('inventory_private.record_warehouse_usage(text)') IS NOT NULL THEN
    RAISE EXCEPTION 'CONDITIONAL_LOCKS_ROLLBACK_VERIFY_FAILED new functions still present';
  END IF;
  PERFORM inventory_private.validate_inventory();
END $cl_rb_post$;
COMMIT;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = {
    '../database/migrations/CONDITIONAL_LOCKS_MIGRATION.sql': buildMigration(),
    '../database/migrations/CONDITIONAL_LOCKS_ROLLBACK.sql': buildRollback(),
  };
  let stale = false;
  for (const [p, body] of Object.entries(out)) {
    const u = new URL(p, import.meta.url);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(u) || fs.readFileSync(u, 'utf8') !== body) {
        console.error('STALE ' + p);
        stale = true;
      }
    } else {
      fs.writeFileSync(u, body);
    }
  }
  if (stale) process.exitCode = 1;
  else console.log(process.argv.includes('--check') ? 'conditional locks migration files up to date' : 'conditional locks migration files written');
}
