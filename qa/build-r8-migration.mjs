// Generates the PREPARED (never auto-run) R8 production migration and its rollback from the reviewed sources:
//   candidate = database/inventory_atomic.sql, rollback target = qa/fixtures/inventory_atomic.main-6933d16.sql (main 6933d16).
// `node qa/build-r8-migration.mjs --check` fails when the committed files drift from the sources (used by CI).
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
export const MAIN_COMMIT_MD5='c10026ce626d134deda991fe78e63057';
export const MAIN_VALIDATE_MD5='e3fdfa9cff80c8b710d6e09d80bfeeab';
// R8-R1 (R2-R8-11): further md5(prosrc) pins of production/main functions the migration replaces or depends on
// (values observed read-only on production by Role 2 / Red Team on 2026-11-11 and equal to the main fixture).
export const MAIN_RESTORE_PREVIEW_MD5='d7c4e0bc52a0b17912326345f0280bb2';
export const MAIN_STATE_HASH_MD5='e743ed68bd86b4619ae3164ef10808ce';
export const CATEGORY_NAMES=['مبيدات حشرية','معقمات ومطهرات','معدات رش ومكافحة','طعوم قوارض','كلور ومواد كيميائية'];
const fnMd5=(name)=>`(SELECT md5(p.prosrc) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='inventory_private' AND p.proname='${name}')`;
export function buildMigration(candidate=read('../database/inventory_atomic.sql')){return `-- R8 readiness — PRODUCTION MIGRATION (PREPARED ONLY; NOT RUN BY ANY AGENT OR CI).
-- Source: database/inventory_atomic.sql on branch qa/r8-readiness-20261109 (generated by qa/build-r8-migration.mjs).
-- Requires separate, explicit owner approval before execution. It changes FUNCTIONS and adds two private tables
-- (inventory_private.material_code_registry, backfilled with existing codes, and inventory_private.category_policy,
-- seeded with the five approved prefixes/ranges). It does NOT update any material, transaction, setting, user or
-- audit row, and does NOT archive or reconcile PES-1001 (PES-1001 stays reported as drift and ordinary changes to it
-- are refused with INVENTORY_RECONCILE_REQUIRED until the separately approved reconcile runs).
--
-- Execution mode: psql -v ON_ERROR_STOP=1 --single-transaction is NOT needed (the file has its own BEGIN/COMMIT);
-- run it in ONE plain session (psql -v ON_ERROR_STOP=1 -f R8_PRODUCTION_MIGRATION.sql), never inside a wrapper
-- that opens its own transaction, and never statement-by-statement in a pooler that may switch sessions.
--
-- Deploy order (see docs/R8_RELEASE_AND_ROLLBACK_AR.md):
--   1. Announce a short no-entry window; every device shows 0 pending / 0 blocked in the sync panel (do NOT erase queues).
--   2. Take and verify the full backup (docs/R8_BACKUP_RESTORE_DRILL_AR.md). Record md5(prosrc) of commit_inventory/validate_inventory.
--   3. Run THIS file once, as one transaction. It stops (and changes nothing) on any baseline drift or policy mismatch.
--   4. Run the read-only check: SELECT public.inventory_projection_drift(); — expect PES-1001 reported as drift (stored 12, ledger 10).
--   5. Deploy the matching client build only after the PR is reviewed/merged by the owner. Old clients remain compatible
--      (server ignores client-supplied derived/lifecycle fields).
--   6. PES-1001 reconcile/archive are SEPARATE approved changes (mode 'reconcile' then mode 'lifecycle'), never part of this file.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(824671520); -- same writer lock as commit_inventory: holds writes for the duration
DO $r8_pre$
DECLARE c text:=${fnMd5('commit_inventory')}; v text:=${fnMd5('validate_inventory')}; rp text:=${fnMd5('restore_preview')}; sh text:=${fnMd5('state_hash')}; cats jsonb; names jsonb; reused jsonb;
BEGIN
 IF c IS DISTINCT FROM '${MAIN_COMMIT_MD5}' OR v IS DISTINCT FROM '${MAIN_VALIDATE_MD5}'
    OR rp IS DISTINCT FROM '${MAIN_RESTORE_PREVIEW_MD5}' OR sh IS DISTINCT FROM '${MAIN_STATE_HASH_MD5}' THEN
   RAISE EXCEPTION 'R8_MIGRATION_BASELINE_DRIFT commit=% validate=% restore_preview=% state_hash=% (expected main 6933d16). Stop and re-review.',c,v,rp,sh;
 END IF;
 -- A pre-existing registry is accepted only with the exact R8 shape (roll-forward after an R8 rollback) and only when
 -- no code it reserves was taken by a DIFFERENT material while rolled back (RT-R8-08): such a conflict is listed and stops.
 IF to_regclass('inventory_private.material_code_registry') IS NOT NULL THEN
   IF (SELECT count(*) FROM information_schema.columns WHERE table_schema='inventory_private' AND table_name='material_code_registry'
        AND column_name IN ('code_key','code','prefix','number','material_id','source','reserved_at'))<>7 THEN
     RAISE EXCEPTION 'R8_MIGRATION_REGISTRY_SHAPE_UNEXPECTED';
   END IF;
   EXECUTE $q$SELECT jsonb_agg(jsonb_build_array(r.code,r.material_id,m.id)) FROM inventory_private.material_code_registry r
     JOIN public.materials m ON lower(btrim(m.data->>'code'))=r.code_key AND m.id<>r.material_id$q$ INTO reused;
   IF reused IS NOT NULL THEN RAISE EXCEPTION 'R8_MIGRATION_CODE_REUSED_DURING_ROLLBACK %',reused; END IF;
 END IF;
 IF to_regclass('inventory_private.category_policy') IS NOT NULL THEN
   EXECUTE $q$SELECT jsonb_agg(jsonb_build_array(prefix,start_range,end_range) ORDER BY prefix) FROM inventory_private.category_policy$q$ INTO cats;
   IF cats IS DISTINCT FROM '[["CHM",5001,5999],["EQP",3001,3999],["PES",1001,1999],["ROD",4001,4999],["SAN",2001,2999]]'::jsonb THEN
     RAISE EXCEPTION 'R8_MIGRATION_POLICY_TABLE_UNEXPECTED %',cats;
   END IF;
 END IF;
 SELECT jsonb_agg(x->>'name' ORDER BY x->>'prefix') INTO names FROM public.settings s, jsonb_array_elements(s.data->'categories') x WHERE s.id='app_config';
 IF names IS DISTINCT FROM '${JSON.stringify([CATEGORY_NAMES[4],CATEGORY_NAMES[2],CATEGORY_NAMES[0],CATEGORY_NAMES[3],CATEGORY_NAMES[1]])}'::jsonb THEN
   RAISE EXCEPTION 'R8_MIGRATION_CATEGORY_NAMES_MISMATCH %',names;
 END IF;
 -- R8-POL-01/02 owner decisions: exactly the five live groups, prefixes and ranges.
 SELECT jsonb_agg(jsonb_build_array(x->>'prefix',(x->>'startRange')::numeric,(x->>'endRange')::numeric) ORDER BY x->>'prefix') INTO cats
   FROM public.settings s, jsonb_array_elements(s.data->'categories') x WHERE s.id='app_config';
 IF cats IS DISTINCT FROM '[["CHM",5001,5999],["EQP",3001,3999],["PES",1001,1999],["ROD",4001,4999],["SAN",2001,2999]]'::jsonb THEN
   RAISE EXCEPTION 'R8_MIGRATION_POLICY_MISMATCH %',cats;
 END IF;
END $r8_pre$;

${candidate}
-- Post-condition inside the same transaction: current data must satisfy the new invariants, otherwise everything rolls back.
DO $r8_post$ BEGIN PERFORM inventory_private.validate_inventory(); END $r8_post$;
COMMIT;
`;}
const dropList=['public.inventory_code_registry()','inventory_private.evaluate_backup_registry(jsonb)','inventory_private.code_registry_export()','inventory_private.projection_status(jsonb,jsonb)','public.inventory_projection_drift()','public.inventory_next_material_code(text)','inventory_private.projection_drift()','inventory_private.next_material_code(text)',
 'inventory_private.reserve_material_code(text,jsonb,jsonb,boolean,text)','inventory_private.code_matches_category(text,text,jsonb)','inventory_private.validate_category_config(jsonb)',
 'inventory_private.material_rows(jsonb)','inventory_private.stored_projection(jsonb)','inventory_private.material_ledger_hash(text)','inventory_private.material_projection(text)',
 'inventory_private.code_parts(text)','inventory_private.server_owned_material_keys()','inventory_private.lifecycle_material_keys()','inventory_private.derived_material_keys()'];
export function buildRollback(main=read('./fixtures/inventory_atomic.main-6933d16.sql')){return `-- R8 readiness — ROLLBACK to main 6933d16 server behaviour (PREPARED ONLY; NOT RUN). Tested in PGlite by qa/r8-migration-rollback.mjs.
-- Restores the exact main functions (commit_inventory md5 ${MAIN_COMMIT_MD5}) and drops the R8 functions.
-- Keeps: every audit receipt (incl. archive/reconcile receipts), every ledger row, current material documents
-- (derived/lifecycle fields stay as inert data), inventory_private.material_code_registry and
-- inventory_private.category_policy (both private, no grants, inert under main).
--
-- WHILE ROLLED BACK (RT-R8-08): main does NOT enforce code non-reuse, the category pin, the drift guard or archive
-- blocking. A code reused in that window is detected by the roll-forward migration, which stops and lists it.
--
-- SAFETY (R8-REC-01 / R2-R8-12): main SQL ignores archive metadata. This file REFUSES to run while any material is
-- archived, unless the operator first reactivates it with the audited lifecycle mode, OR confirms a write hold by
-- running in the same session:
--     SET r8.rollback_hold_writes = 'confirmed';
-- On that path the hold is ENFORCED on EVERY write path main exposes (R8-R2 / RT-R8-D02): EXECUTE on the public
-- wrapper public.inventory_commit AND on the definer inventory_private.commit_inventory (which also carries main's
-- audit/login/logout receipts) is revoked from authenticated at the end of this file. Direct table DML is already
-- revoked from authenticated/anon by main. No device or direct RPC can write until roll-forward (which re-grants both)
-- or an explicit, approved re-grant of BOTH:
--     GRANT EXECUTE ON FUNCTION inventory_private.commit_inventory(text,jsonb) TO authenticated;
--     GRANT EXECUTE ON FUNCTION public.inventory_commit(text,jsonb) TO authenticated;
-- The file also prints (NOTICE R8_ROLLBACK_HOLD_OTHER_EXECUTABLE) any other VOLATILE function in public or
-- inventory_private still executable by authenticated, for the operator to review (expected: only the read-only
-- restore preview). Confirm in the dashboard (API -> Exposed schemas) that inventory_private is NOT exposed.
BEGIN;
SET LOCAL lock_timeout = '5s';
SELECT pg_advisory_xact_lock(824671520);
DO $r8_rb_pre$
BEGIN
 IF EXISTS(SELECT 1 FROM public.materials WHERE data->>'lifecycleStatus'='archived')
    AND coalesce(current_setting('r8.rollback_hold_writes',true),'')<>'confirmed' THEN
   RAISE EXCEPTION 'R8_ROLLBACK_BLOCKED_ARCHIVED_MATERIALS: reactivate first or confirm a write hold';
 END IF;
END $r8_rb_pre$;

${main}
${dropList.map(f=>`DROP FUNCTION IF EXISTS ${f};`).join('\n')}
-- inventory_private.material_code_registry and inventory_private.category_policy are intentionally KEPT (private, no grants).
DO $r8_rb_hold$
BEGIN
 IF EXISTS(SELECT 1 FROM public.materials WHERE data->>'lifecycleStatus'='archived') THEN
   REVOKE EXECUTE ON FUNCTION public.inventory_commit(text,jsonb) FROM authenticated;
   REVOKE EXECUTE ON FUNCTION inventory_private.commit_inventory(text,jsonb) FROM authenticated;
   RAISE NOTICE 'R8_ROLLBACK_WRITE_HOLD_ENFORCED: public.inventory_commit and inventory_private.commit_inventory revoked from authenticated until roll-forward or approved re-grant';
   RAISE NOTICE 'R8_ROLLBACK_HOLD_OTHER_EXECUTABLE %',(SELECT coalesce(jsonb_agg(n.nspname||'.'||p.proname ORDER BY n.nspname,p.proname),'[]'::jsonb)
     FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
     WHERE n.nspname IN ('public','inventory_private') AND p.provolatile='v' AND has_function_privilege('authenticated',p.oid,'EXECUTE'));
 END IF;
END $r8_rb_hold$;

DO $r8_rb_post$
BEGIN
 IF ${fnMd5('commit_inventory')} IS DISTINCT FROM '${MAIN_COMMIT_MD5}' OR ${fnMd5('validate_inventory')} IS DISTINCT FROM '${MAIN_VALIDATE_MD5}' THEN
   RAISE EXCEPTION 'R8_ROLLBACK_VERIFY_FAILED';
 END IF;
END $r8_rb_post$;
COMMIT;
`;}
if(import.meta.url===`file://${process.argv[1]}`){
 const out={'../database/migrations/R8_PRODUCTION_MIGRATION.sql':buildMigration(),'../database/migrations/R8_ROLLBACK.sql':buildRollback()};
 let stale=false;
 for(const [p,body] of Object.entries(out)){const u=new URL(p,import.meta.url);
  if(process.argv.includes('--check')){if(!fs.existsSync(u)||fs.readFileSync(u,'utf8')!==body){console.error('STALE '+p);stale=true;}}
  else fs.writeFileSync(u,body);}
 if(stale)process.exitCode=1;else console.log(process.argv.includes('--check')?'migration files up to date':'migration files written');
}
